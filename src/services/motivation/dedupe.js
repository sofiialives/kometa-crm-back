/**
 * Защита ручных операций от повторов.
 *
 * Форма на фронте при каждом открытии придумывает свой ключ запроса и
 * отправляет его вместе с данными. В журнал он ложится как dedupeKey
 * «request:ключ:сотрудник», а у этой колонки уникальный индекс. Поэтому
 * двойное нажатие кнопки или повтор запроса после обрыва связи упираются в
 * базу: второй раз деньги не положатся и баллы не начислятся.
 *
 * Без ключа (старый клиент, ручной запрос) операция проходит как раньше —
 * защита добавочная, а не обязательная.
 */

export function requestKeyFor(requestKey, userId) {
  return requestKey ? `request:${requestKey}:${userId}` : null
}

/** Это повтор уже выполненного запроса, а не другая ошибка базы. */
export function isDuplicate(error, requestKey) {
  return Boolean(requestKey) && error?.code === 'P2002'
}
