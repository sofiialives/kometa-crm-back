/**
 * Как бот пишет: без «нейронных» знаков. Общие правила для ответов агента
 * и отчётов по поручениям.
 */

/**
 * Ответ модели в стиле остальных сообщений бота. Модель просим об этом в
 * подсказке, а тут подчищаем, если всё же написала по-своему: смайлики,
 * длинные тире, скобки посреди фразы, восклицания, двоеточия перед
 * пояснением, звёздочки и решётки, списки через дефис. Скобки перед
 * именем — это «(Отдел) Имя», их оставляем.
 */
export function plainStyle(text) {
  return String(text ?? '')
    .replace(/[\p{Extended_Pictographic}\u{FE0F}\u{200D}]/gu, '')
    .replace(/\*\*|__|^#{1,6}[ \t]+/gm, '')
    .replace(/^[ \t]*[-—–*•][ \t]+/gm, '• ')
    .replace(/^[ \t]*\d{1,2}[.)][ \t]+/gm, '• ')
    .replace(/[ \t]+[—–][ \t]+/g, ', ')
    .replace(/([^\s•(\n])[ \t]*\(([^()\n]{1,80})\)(?![ \t]+[A-ZА-ЯЁ])/g, '$1, $2')
    .replace(/!+/g, '.')
    .replace(/\?\./g, '?')
    .replace(/([^\d\s]):[ \t]*\n/g, '$1\n')
    .replace(/([^\d\s]):[ \t]+/g, '$1, ')
    .replace(/,\s*([,.?])/g, '$1')
    .replace(/\.{2,}/g, '.')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** Без ссылок и упоминаний: телеграм делает их кликабельными, даже голый домен. */
export function noLinks(text) {
  return String(text ?? '')
    .replace(/(?:https?|hxxps?|tg):\/\/\S+/gi, '[ссылка]')
    .replace(/\b(?:t\.me|telegram\.me|www\.)\S*/gi, '[ссылка]')
    .replace(/\b[\w-]+(?:\.[\w-]+)*\.(?:ru|com|net|org|io|me|su|рф|app|dev|site|online|info|biz|xyz|pro|ua|by|kz)\b\S*/gi, '[ссылка]')
    .replace(/@\w{3,}/g, '[упоминание]')
}
