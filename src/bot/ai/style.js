/**
 * Как бот пишет: без «нейронных» знаков. Общие правила для ответов агента
 * и отчётов по поручениям.
 */

/**
 * Ответ модели в стиле остальных сообщений бота. Модель просим об этом в
 * подсказке, а тут подчищаем, если всё же написала по-своему: смайлики,
 * длинные тире, скобки, восклицания, двоеточия перед пояснением, звёздочки
 * и решётки, маркеры и нумерация в начале строк, точка в конце строки.
 * Время 15:30 и ссылки остаются, многоточие и сокращения вроде «т.д.»
 * внутри фразы тоже.
 *
 * Чистка может склеить куски текста, поэтому noLinks всегда идёт после неё:
 * noLinks(plainStyle(text)).
 */
const NUMBERED = /^[ \t]*\d{1,2}[.)][ \t]+/

/**
 * Нумерацию в начале строк снимаем, только если подряд хотя бы две строки с
 * номерами: «12. Ноября встреча» одна и остаётся как есть.
 */
function stripNumbering(text) {
  const lines = text.split('\n')
  for (let i = 0; i < lines.length;) {
    let j = i
    while (j < lines.length && NUMBERED.test(lines[j])) j += 1
    if (j - i >= 2) for (let k = i; k < j; k += 1) lines[k] = lines[k].replace(NUMBERED, '')
    i = Math.max(j, i + 1)
  }
  return lines.join('\n')
}

export function plainStyle(text) {
  return stripNumbering(String(text ?? ''))
    .replace(/[\p{Extended_Pictographic}\u{FE0F}\u{200D}]/gu, '')
    .replace(/(^|\s)[:;]-?[)(]+/g, '$1')
    .replace(/\*\*|__|^#{1,6}[ \t]+/gm, '')
    .replace(/^[ \t]*[-—–*•][ \t]+/gm, '')
    // Одиночные *звёздочки* и _подчёркивания_ вокруг слов.
    .replace(/(?<![\p{L}\d*])\*(?=[^\s*])([^*\n]+?)(?<=[^\s*])\*(?![\p{L}\d*])/gu, '$1')
    .replace(/(?<![\p{L}\d_])_(?=[^\s_])([^_\n]+?)(?<=[^\s_])_(?![\p{L}\d_])/gu, '$1')
    .replace(/[ \t]+[—–][ \t]+/g, ', ')
    // «рад(а)», «готов(а)» — окончание в скобках просто убираем.
    .replace(/(?<=\p{L})\([а-яё]{1,2}\)/gu, '')
    // Скобки вплотную к тексту с двух сторон («t(.)me») заменяем пробелами, а не
    // склеиваем: убрав их, можно собрать рабочую ссылку.
    .replace(/(?<=\S)\(([^()\n]{1,120})\)(?=\S)/g, ' $1 ')
    // «Иван(дизайн) сказал» — скобка вплотную к слову: пробел, а не склейка.
    .replace(/(?<=[^\s(])\(([^()\n]{1,120})\)/g, ' $1')
    // Скобки: если за ними идёт слово, это часть фразы, иначе пояснение через запятую.
    .replace(/\(([^()\n]{1,120})\)(?=[ \t]+\p{L})/gu, '$1')
    .replace(/([^\s(\n])[ \t]*\(([^()\n]{1,120})\)/g, '$1, $2')
    .replace(/\(([^()\n]{1,120})\)/g, '$1')
    .replace(/[()]/g, ' ')
    .replace(/!+\?+/g, '?')
    .replace(/!+/g, '.')
    .replace(/\?\./g, '?')
    // Двоеточие в конце строки пропадает, перед пояснением становится запятой.
    // Время (15:30) и ссылки (https://) не затрагиваются: после их двоеточия не пробел.
    .replace(/:[ \t]*(?=\n|$)/g, '')
    .replace(/:[ \t]+/g, ', ')
    .replace(/,\s*([,.?])/g, '$1')
    .replace(/\.{4,}/g, '...')
    .replace(/(?<!\.)\.\.(?!\.)/g, '.')
    // Точка в конце строки. Многоточие и «т.д.» остаются.
    .replace(/(?<![.\s]|(?:^|[\s(«"])\p{L}\.\p{L})\.[ \t]*(?=\n|$)/gmu, '')
    .replace(/[ \t]{2,}/g, ' ')
    .replace(/[ \t]+$/gm, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim()
}

/** Без ссылок и упоминаний: телеграм делает их кликабельными, даже голый домен. */
export function noLinks(text) {
  return String(text ?? '')
    .replace(/(?:https?|hxxps?|tg):\/\/\S+/gi, '[ссылка]')
    .replace(/\b(?:t\.me|telegram\.me|www\.)\S*/gi, '[ссылка]')
    .replace(/(?<![\p{L}\d.-])[\p{L}\d-]+(?:\.[\p{L}\d-]+)*\.(?:ru|com|net|org|io|me|su|рф|app|dev|site|online|info|biz|xyz|pro|ua|by|kz|ly|co|uk|de|us|gg|to|cc|tv|ai|link|page)(?![\p{L}\d])\S*/giu, '[ссылка]')
    .replace(/@\w{3,}/g, '[упоминание]')
}
