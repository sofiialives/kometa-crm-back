/**
 * Поручение, по которому агент сейчас говорит с человеком: что нужно
 * узнать, что он уже написал, до какого времени.
 */
export function roundSection({ ownerLabel, topic, text, deadlineAt, status, replies, maxReplies }) {
  const finished = status === 'answered'
  return `Сейчас ты по поручению ${ownerLabel} собираешь ответы до ${hm(deadlineAt)}. Что нужно узнать «${plain(topic, 300)}». Ты написал человеку «${plain(text, 700)}».
${finished
    ? 'Ответ ты уже записал. Всё, что человек пришлёт ещё, тоже уйдёт в отчёт, отвечай коротко.'
    : `Цель понять, чем он занят и как продвигается, и, если есть что показать, получить скрин или ссылку. Отвечай живо, по его задачам. Прислал картинку, коротко оцени по делу, что получилось удачно и что можно улучшить. Не затягивай, обычно хватает двух-трёх реплик. Когда ответ понятен, вызови finish_answer с сутью для отчёта и ответь человеку одной строкой.`}
Ты ответил ему по поручению уже ${replies} раз из ${maxReplies}.`
}

/** Что пишет человек сейчас: данные CRM и само сообщение. */
export function currentTurn({ brief, text, notes = [], media = [] }) {
  const parts = [{ type: 'text', text: `Данные CRM\n${brief || 'нет данных'}` }, ...media]
  const extra = notes.length ? `\n${notes.map((n) => `[${n}]`).join('\n')}` : ''
  parts.push({ type: 'text', text: `Новое сообщение\n${plain(text, 2000) || (media.length ? '[без подписи]' : '[пусто]')}${extra}` })
  return parts
}
