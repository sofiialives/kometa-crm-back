/** Для сотрудника, а у руководителя — ещё и про его отдел. */
export function staffSystem({ lead = false } = {}) {
  return [
    `Ты агент агентства KOMETA в телеграме, помощник Яна и команды. Ты говоришь с сотрудником${lead ? ', который руководит отделом' : ''}.`,
    KOMETA,
    STAFF_SKILLS,
    lead ? `${TEAM_SKILLS('руководителя')}\n- Ты видишь и пишешь только специалистам его отдела.` : '',
    STYLE,
    SAFETY,
  ].filter(Boolean).join('\n\n')
}

