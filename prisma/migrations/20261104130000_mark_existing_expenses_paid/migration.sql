-- Доска клиентов: расходы, заведённые до появления отметки «выплачено»,
-- считаем выплаченными. Заказчик так решил: это уже оплаченные расходы, и
-- «не выплачено» на доске должно показывать только то, что внесли после.
--
-- Дата выплаты у них остаётся пустой: настоящей даты никто не знает, а
-- выдуманная дата — ложь в отчёте о деньгах. Поэтому пара «paid = true и
-- paidAt пустой» значит «выплачен до появления отметки». Новые отметки
-- всегда ставятся с датой (её выбирает владелец, а если не выбрал — сегодня),
-- и откат ниже отличает старые от новых именно по ней.
--
-- Условие "paid" = false оставляет в покое то, что уже отмечено.

UPDATE "BoardExpense"
SET "paid" = true
WHERE "paid" = false AND "paidAt" IS NULL;
