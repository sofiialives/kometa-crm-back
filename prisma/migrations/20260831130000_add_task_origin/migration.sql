-- Задача из Иерархии после удаления её работы (work.service.js /
-- client.service.js специально обнуляют workId, чтобы не терять историю
-- задач) становилась неотличима от обычной личной задачи и протекала
-- в личный Задачник. workId для этого ненадёжен в принципе — он меняется
-- после создания. Нужен отдельный признак, который проставляется один
-- раз и больше никогда не трогается.

-- 1. Новый тип
CREATE TYPE "TaskOrigin" AS ENUM ('personal', 'hierarchy');

-- 2. Колонка с безопасным дефолтом — ничего не ломает у существующих строк
ALTER TABLE "Task" ADD COLUMN "origin" "TaskOrigin" NOT NULL DEFAULT 'personal';

-- 3. Бэкафилл по лучшему доступному сигналу: если у задачи СЕЙЧАС есть
-- workId — она точно из Иерархии, помечаем.
-- Важная честная оговорка: задачи, чья работа была удалена ДО этой
-- миграции, уже имеют workId = null, и по ним восстановить происхождение
-- нечем — информация была потеряна раньше, не в этой миграции. Такие
-- придётся один раз найти и убрать глазами (см. инструкцию у Клода в
-- сообщении, звучит как "Отчёт по кампании", "Финальная таблица" и т.д.)
UPDATE "Task" SET "origin" = 'hierarchy' WHERE "workId" IS NOT NULL;
