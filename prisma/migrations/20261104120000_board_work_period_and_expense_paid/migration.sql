-- Доска клиентов: срок работ по услуге и отметка «выплачено» у расхода.
--
-- Миграция написана РУКАМИ, как и все предыдущие здесь: сгенерированная
-- потащила бы за собой то, что есть на проде, но отсутствует в истории
-- миграций, а render.yaml гоняет migrate deploy в buildCommand.
--
-- Только новые колонки, существующие строки не трогаются:
--  * workFrom / workTo необязательные. Пусто значит «весь месяц услуги»,
--    поэтому старые услуги ведут себя ровно как раньше;
--  * paid получает значение по умолчанию false: все прежние расходы
--    считаются невыплаченными, пока админ не поставит галочку;
--  * paidAt необязательный, у прежних расходов даты нет.

ALTER TABLE "BoardService"
ADD COLUMN "workFrom" TIMESTAMP(3),
ADD COLUMN "workTo" TIMESTAMP(3);

ALTER TABLE "BoardExpense"
ADD COLUMN "paid" BOOLEAN NOT NULL DEFAULT false,
ADD COLUMN "paidAt" TIMESTAMP(3);
